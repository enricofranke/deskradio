export const TEXTS: Record<Language, Record<TextKey, string>> = { de: DE, en: EN };

export function t(key: TextKey, vars: Record<string, string | number> = {}, language: Language = env.language): string {
  return TEXTS[language][key].replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
